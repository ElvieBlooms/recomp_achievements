-- tools/gen_coverage.lua
-- Writes docs/COVERAGE.md: every official RA entry for Red, Blue,
-- Yellow, Gold, Silver and Crystal, the rule that tracks it, how (state / event / session tracker),
-- whether an old save gets credit, and any interpretation note.
--
--   luajit tools/gen_coverage.lua            (from the project folder)

local root = (arg and arg[1]) or "."
local mod = root .. "/recomp_achievements"
local rules = dofile(mod .. "/rules/gen1_official.lua")(dofile(mod .. "/rules/gen1_lib.lua"))
for _, r in ipairs(dofile(mod .. "/rules/gen2_official.lua")(dofile(mod .. "/rules/gen2_lib.lua"))) do
  rules[#rules + 1] = r
end

local function catalog(game)
  local f = assert(loadfile(mod .. "/catalog/" .. game .. ".lua"))
  setfenv(f, {})
  return f()
end

local byGameId = {}
for _, r in ipairs(rules) do
  for game, id in pairs(r.ra or {}) do
    byGameId[game] = byGameId[game] or {}
    byGameId[game][id] = r
  end
end

local function how(r)
  if r.kind == "state" then return "save state", "yes" end
  if r.kind == "event" then return "event", r.check and "yes" or "no" end
  return "session", r.check and "yes" or "no"
end

local function md(s)
  return (tostring(s or ""):gsub("|", "/"):gsub("\n", " "))
end

local out = {}
local function w(line) out[#out + 1] = line end
w("# Coverage: RetroAchievements lists")
w("")
w("Generated by `tools/gen_coverage.lua` from `rules/gen1_official.lua`,")
w("`rules/gen2_official.lua` and the")
w("bundled catalogs. Titles and descriptions are RetroAchievements metadata,")
w("credited to RetroAchievements and each achievement's author. The detection")
w("logic is this mod's own.")
w("")
w("- **How**: *save state* is read from the save, so an existing save is")
w("  credited when it loads. *event* reacts to something happening in play.")
w("  *session* follows a run within one play session; loading a save resets")
w("  it, which is how \"without resetting\" is enforced.")
w("- **Old saves**: whether a save made before installing the mod gets credit.")
w("- **Exact** means the check matches the RA description. **Local reading**")
w("  means it is this mod's closest reading of it, explained in the note")
w("  (also shown in game on the achievement's ABOUT page).")
w("")

local totals = {}
for _, game in ipairs({ "red", "blue", "yellow", "gold", "silver", "crystal" }) do
  local c = catalog(game)
  local exact, interp, n = 0, 0, 0
  w(("## %s (RA game %d)"):format(c.title or game, c.gameId))
  w("")
  w("| RA id | Achievement | Pts | How | Old saves | Fidelity | Note |")
  w("|---:|---|---:|---|---|---|---|")
  for _, e in ipairs(c.entries) do
    local r = byGameId[game] and byGameId[game][e.id]
    if r then
      n = n + 1
      local kind, old = how(r)
      local fid = r.fidelity == "interpretation" and "Local reading" or "Exact"
      if r.fidelity == "interpretation" then interp = interp + 1 else exact = exact + 1 end
      w(("| %d | **%s** - %s | %d | %s | %s | %s | %s |"):format(e.id, md(e.title), md(e.description),
        e.points, kind, old, fid, md(r.note)))
    else
      w(("| %d | **%s** - %s | %d | not tracked | - | - | |"):format(e.id, md(e.title), md(e.description), e.points))
    end
  end
  w("")
  totals[#totals + 1] = ("| %s | %d | %d | %d | %d |"):format(c.title or game, #c.entries, n, exact, interp)
end

-- the summary goes right before the first game section
local at = 1
for i, line in ipairs(out) do if line:find("^## ") then at = i break end end
local summary = { "## Summary", "", "| Game | RA entries | Tracked | Exact | Local reading |",
  "|---|---:|---:|---:|---:|" }
for _, line in ipairs(totals) do summary[#summary + 1] = line end
summary[#summary + 1] = ""
for i = #summary, 1, -1 do table.insert(out, at, summary[i]) end

local f = assert(io.open(root .. "/docs/COVERAGE.md", "w"))
f:write(table.concat(out, "\n"), "\n")
f:close()
print("wrote docs/COVERAGE.md")
for _, t in ipairs(totals) do print(t) end
